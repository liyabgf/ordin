#!/usr/bin/env node
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { existsSync, mkdtempSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { createServer } from 'node:net'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { setTimeout as delay } from 'node:timers/promises'
import { ProcessRegistry } from '../src/app/process.ts'
import { boot } from '../src/app/boot.ts'
import { resolveConfig } from '../src/app/config.ts'
import { silentLogger } from '../src/app/logger.ts'
import { createRuntime } from '../src/app/runtime.ts'

const [durationArg = '600000', sampleArg = '10000'] = process.argv.slice(2)
const durationMs = Number(durationArg)
const sampleMs = Number(sampleArg)
assert(process.argv.length <= 4 && Number.isSafeInteger(durationMs) && durationMs >= 10_000
  && Number.isSafeInteger(sampleMs) && sampleMs >= 1000 && sampleMs <= durationMs / 3,
'Usage: node --experimental-transform-types scripts/measure-long-run.mjs [duration-ms >= 10000] [1000 <= sample-ms <= duration-ms / 3]')
assert.notEqual(process.platform, 'win32', 'This fixture checks POSIX process groups')

const EVENT_CAP = 500
const HISTORY_CAP = 64
const OUTPUT_CAP = 8 * 1024 * 1024
const HEAVY_BYTES = 1024 * 1024
const outputDir = mkdtempSync(join(realpathSync(tmpdir()), 'ordin-r5-evidence.'))
const stateDir = mkdtempSync(join(realpathSync(tmpdir()), 'ordin-r5-state.'))
const proc = new ProcessRegistry()
const logger = silentLogger()
const initialExitListeners = process.listenerCount('exit')
const report = { startedAt: new Date().toISOString(), stateDir, durationMs, sampleMs, samples: [], cleanup: {}, errors: [] }
console.log(JSON.stringify({ outputDir, stateDir, durationMs, sampleMs }))

function spawn(code) {
  return proc.spawn({ owner: 'r5-measurement', argv: [process.execPath, '-e', code], timeoutMs: 15_000 })
}

async function finishChild(bytes) {
  const child = spawn('process.stdout.write(Buffer.alloc(' + bytes + ', 120))')
  const outcome = await proc.wait(child.id)
  assert.equal(outcome.status, 'exited', JSON.stringify(outcome))
  assert.equal(outcome.exitCode, 0, JSON.stringify(outcome))
  assert.equal(outcome.exitSignal, null, JSON.stringify(outcome))
  assert.equal(Buffer.byteLength(child.stdout), bytes, 'child capture differs from generated bytes')
  assert.equal(child.stdoutTruncated, false)
  completedChildren += 1
  return child.id
}

function retainedOutput(records) {
  return records.reduce((total, item) => total + Buffer.byteLength(item.stdout)
    + Buffer.byteLength(item.stderr) + Buffer.byteLength(item.error ?? ''), 0)
}

async function rebind(port) {
  const server = createServer()
  await new Promise((resolve, reject) => {
    server.once('error', reject)
    server.listen(port, '127.0.0.1', resolve)
  })
  await new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve()))
}

function stateFingerprint() {
  return readdirSync(stateDir, { recursive: true, withFileTypes: true })
    .filter(entry => entry.isFile())
    .map(entry => {
      const path = join(entry.parentPath, entry.name)
      return [path, createHash('sha256').update(readFileSync(path)).digest('hex')]
    })
    .sort((a, b) => a[0].localeCompare(b[0]))
}

let bootstrap
let runtime
let port
let liveChild
let unsubscribe
let shutdownConfirmed = false
let completedChildren = 0
try {
  bootstrap = boot({ config: resolveConfig({
    stateDir, workRoot: join(stateDir, 'work'), inboxDir: join(stateDir, 'inbox'), port: 0,
  }), logger })
  const forbidden = () => { throw new Error('Fixture attempted to dispatch a Worker or call a model') }
  runtime = createRuntime(bootstrap, {
    logger, driver: new Proxy({}, { get: () => forbidden }), proc, notifier: null,
    acceptanceEnabled: false, fetchFn: forbidden,
  })
  await runtime.start()
  port = runtime.serverPort()
  assert(port > 0, 'Runtime did not bind a port')
  assert(existsSync(join(stateDir, 'ordin.lock')), 'Runtime did not acquire the state lock')
  const runningExitListeners = process.listenerCount('exit')
  assert.equal(runningExitListeners, initialExitListeners + 1, 'unexpected running exit listener count')

  // Runtime uses a TypeScript-private Set here. This probe measures just this domain subscription set.
  assert(runtime.listeners instanceof Set && typeof runtime.subscribe === 'function', 'Runtime subscription probe no longer matches implementation')
  const initialSubscribers = runtime.listeners.size
  unsubscribe = runtime.subscribe(() => {})
  assert.equal(runtime.listeners.size, initialSubscribers + 1)
  runtime.saveSettings({ acceptMode: 'auto' })
  const created = runtime.engine.createTicket({ title: 'R5 isolated measurement', text: 'Synthetic progress fixture' })
  runtime.saveSettings({ paused: true })
  assert.equal(created.disposition.state, 'accepted', JSON.stringify(created.disposition))
  assert(created.ticketId, 'accepted measurement Ticket has no ID')
  const ticket = runtime.store.tickets.get(created.ticketId)
  assert(ticket, 'measurement Ticket was not persisted')
  const listEvents = () => runtime.store.events.list(ticket.id)
  const baselineEvents = listEvents().filter(event => event.type !== 'worker_text').map(event => event.seq)
  assert(baselineEvents.length > 0, 'no domain history to test for preservation')

  let writtenEvents = 0
  function writeProgress(count) {
    for (let index = 0; index < count; index += 1) {
      writtenEvents += 1
      runtime.store.events.append({ ticketId: ticket.id, type: 'worker_text', at: new Date().toISOString(),
        detail: { assignmentId: 'synthetic-r5', attemptId: 'synthetic-r5', text: 'progress-' + writtenEvents },
      })
    }
  }
  function checkEvents() {
    const events = listEvents()
    const progress = events.filter(event => event.type === 'worker_text')
    assert.equal(progress.length, EVENT_CAP, 'Worker progress retention count')
    assert.equal(progress[0].detail.text, 'progress-' + (writtenEvents - EVENT_CAP + 1), 'oldest retained progress')
    assert.equal(progress.at(-1).detail.text, 'progress-' + writtenEvents, 'newest retained progress')
    const domain = new Set(events.filter(event => event.type !== 'worker_text').map(event => event.seq))
    assert(baselineEvents.every(seq => domain.has(seq)), 'original domain history disappeared')
    return progress.length
  }

  writeProgress(EVENT_CAP + 25)
  report.eventPressure = { written: writtenEvents, retained: checkEvents() }
  const firstSmall = await finishChild(1)
  for (let i = 0; i < HISTORY_CAP; i += 1) await finishChild(1)
  assert.equal(proc.list().length, HISTORY_CAP, 'settled process history count')
  assert.equal(proc.get(firstSmall), undefined, 'oldest small process was retained')
  report.historyPressure = { completed: HISTORY_CAP + 1, retained: proc.list().length }

  const firstHeavy = await finishChild(HEAVY_BYTES)
  for (let i = 0; i < OUTPUT_CAP / HEAVY_BYTES; i += 1) await finishChild(HEAVY_BYTES)
  assert.equal(retainedOutput(proc.list()), OUTPUT_CAP, 'settled output byte budget')
  assert.equal(proc.get(firstHeavy), undefined, 'oldest heavy process was retained')
  report.outputPressure = { generatedBytes: OUTPUT_CAP + HEAVY_BYTES, retainedBytes: retainedOutput(proc.list()) }

  const began = performance.now()
  do {
    writeProgress(25)
    await finishChild(HEAVY_BYTES)
    const records = proc.list()
    const sample = {
      elapsedMs: Math.round(performance.now() - began), rssBytes: process.memoryUsage.rss(),
      retainedEvents: checkEvents(), retainedProcesses: records.length, retainedOutputBytes: retainedOutput(records),
      exitListeners: process.listenerCount('exit'), domainSubscribers: runtime.listeners.size,
      writtenEvents, completedChildren,
    }
    assert(records.every(record => record.status === 'exited'), 'a sampled child did not settle successfully')
    assert(sample.retainedProcesses <= HISTORY_CAP && sample.retainedOutputBytes <= OUTPUT_CAP, 'process retention exceeded its cap')
    assert.equal(sample.exitListeners, runningExitListeners, 'exit listeners changed during sampling')
    assert.equal(sample.domainSubscribers, initialSubscribers + 1, 'subscriptions changed during sampling')
    report.samples.push(sample)
    await delay(Math.min(sampleMs, Math.max(0, durationMs - (performance.now() - began))))
  } while (performance.now() - began < durationMs)
  report.elapsedMs = Math.round(performance.now() - began)
  assert(report.samples.length >= 2, 'fewer than two samples')

  unsubscribe()
  unsubscribe = undefined
  assert.equal(runtime.listeners.size, initialSubscribers, 'fixture subscription was retained')
  report.subscription = { initial: initialSubscribers, during: initialSubscribers + 1, afterDispose: runtime.listeners.size }

  liveChild = spawn('setInterval(() => {}, 1000)')
  assert(liveChild.pid, 'shutdown fixture child did not spawn')
  process.kill(-liveChild.pid, 0)
} catch (error) {
  report.errors.push(String(error.stack ?? error))
} finally {
  unsubscribe?.()
  try {
    await proc.stopAll(250)
    assert(proc.list().every(record => record.status !== 'running'), 'registry still has running children')
    if (liveChild?.pid) {
      const outcome = await proc.wait(liveChild.id)
      assert.equal(outcome.status, 'stopped', JSON.stringify(outcome))
      assert.throws(() => process.kill(-liveChild.pid, 0), { code: 'ESRCH' }, 'shutdown fixture process group still exists')
      report.cleanup.processGroupReleased = true
      report.cleanup.stopOutcome = outcome
    }
  } catch (error) {
    report.errors.push(String(error.stack ?? error))
  }
  try {
    if (runtime) await runtime.stop()
    else if (bootstrap) await bootstrap.stop()
    shutdownConfirmed = true
    assert.equal(process.listenerCount('exit'), initialExitListeners, 'exit listeners did not return to baseline')
    assert(!existsSync(join(stateDir, 'ordin.lock')), 'state lock remains after shutdown')
    report.cleanup.exitListenersBeforeBoot = initialExitListeners
    report.cleanup.exitListenersAfterStop = process.listenerCount('exit')
    report.cleanup.lockReleased = true
    if (port) {
      await rebind(port)
      report.cleanup.portRebound = port
    }
    const stopped = stateFingerprint()
    await delay(1000)
    assert.deepEqual(stateFingerprint(), stopped, 'isolated state changed after shutdown')
    report.cleanup.postStopStableMs = 1000
  } catch (error) {
    report.errors.push(String(error.stack ?? error))
  }
  if (shutdownConfirmed && report.errors.length === 0) {
    rmSync(stateDir, { recursive: true })
    report.cleanup.stateDirRemoved = !existsSync(stateDir)
    assert(report.cleanup.stateDirRemoved)
  }
  report.finishedAt = new Date().toISOString()
  const keys = Object.keys(report.samples[0] ?? {})
  writeFileSync(join(outputDir, 'samples.json'), JSON.stringify(report, null, 2) + '\n')
  writeFileSync(join(outputDir, 'samples.csv'), [keys.join(','), ...report.samples.map(sample => keys.map(key => sample[key]).join(','))].join('\n') + '\n')
  for (const error of report.errors) console.error(error)
  console.log(JSON.stringify({ outputDir, samples: report.samples.length, cleanup: report.cleanup, ok: report.errors.length === 0 }))
  process.exitCode = report.errors.length === 0 ? 0 : 1
}
